// GF(2^8) doubling under the AES polynomial 0x11b.
static inline uint8_t aes_xtime2(uint8_t x) {
  return (uint8_t)((x << 1) ^ ((x & 0x80) ? 0x1b : 0x00));
}

// MixColumns contribution of one byte: column [2s, s, s, 3s], packed
// little-endian so row 0 (2s) lands in the low byte.
static inline uint32_t aes_mixcol_byte(uint8_t s) {
  uint8_t s2 = aes_xtime2(s);
  uint8_t s3 = (uint8_t)(s2 ^ s);
  return ((uint32_t)s3 << 24) | ((uint32_t)s << 16) | ((uint32_t)s << 8) | s2;
}

static inline uint32_t rol32(uint32_t x, uint32_t n) {
  n &= 31;
  return n ? ((x << n) | (x >> (32 - n))) : x;
}

SymUnit::SymUnit(const SimContext& ctx, const char* name, Core* core)
  : FuncUnit<VX_CFG_NUM_SYM_BLOCKS>(ctx, name, core)
{}

uint32_t SymUnit::latency_of(const instr_trace_t* trace) const {
  if (std::get_if<SymType>(&trace->op_type)) {
    // Single-cycle combinational datapath plus the output elastic buffer,
    // matching the ALU's single-cycle ops.
    return 2;
  }
  std::abort();
}

void SymUnit::execute(instr_trace_t* trace) {
  auto& tmask = trace->tmask;
  auto& instr = *trace->instr_ptr;
  auto instrArgs = instr.get_args();
  uint32_t num_threads = VX_CFG_NUM_THREADS;
  auto& rs1_data = trace->src_data[0];
  auto& rs2_data = trace->src_data[1];

  trace->dst_data.assign(num_threads, reg_data_t{});
  auto& rd_data = trace->dst_data;

  auto sym_type = std::get<SymType>(trace->op_type);
  auto symArgs = std::get<IntrSymArgs>(instrArgs);
  uint32_t bs = symArgs.bs & 0x3;

  for (uint32_t t = 0; t < num_threads; ++t) {
    if (!tmask.test(t))
      continue;
    uint32_t a = (uint32_t)rs1_data[t].u;
    uint32_t b = (uint32_t)rs2_data[t].u;
    uint8_t sel = (uint8_t)((b >> (8 * bs)) & 0xff);
    uint8_t sb = kAesSbox[sel];
    uint32_t so = (sym_type == SymType::AES32ESMI) ? aes_mixcol_byte(sb) : (uint32_t)sb;
    rd_data[t].u = a ^ rol32(so, 8 * bs);
  }
}

void SymUnit::on_tick() {
  for (uint32_t b = 0; b < VX_CFG_NUM_SYM_BLOCKS; ++b) {
    auto& input = Inputs.at(b);
    if (input.empty())
      continue;
    auto& output = Outputs.at(b);
    if (output.full())
      continue; // stall
    auto trace = input.peek();
    this->execute(trace);
    uint32_t delay = this->latency_of(trace);
    output.send(trace, delay);
    input.pop();
  }
}

